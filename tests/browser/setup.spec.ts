import { test, expect, type Page } from '@playwright/test'

const button = (page: Page, name: string) => page.getByRole('button', { name, exact: true })
const nav = (page: Page) => page.getByRole('navigation', { name: 'Langkah persiapan' })
const step = (page: Page, name: string) => nav(page).getByRole('button', { name, exact: true })

test('setup advances one step at a time and keeps edits across navigation and settings', async ({ page }) => {
  await page.goto('./')
  await button(page, 'Mulai bermain').click()
  await expect(step(page, 'Pemain')).toHaveAttribute('aria-current', 'step')
  await button(page, 'Lanjut').click()
  await expect(step(page, 'Peran')).toHaveAttribute('aria-current', 'step')
  await expect(page.getByText(/Pilihan mode|Kacau ringan/i)).toHaveCount(0)
  await expect(page.getByRole('combobox', { name: 'Sumber kata' })).toHaveCount(0)
  await page.getByRole('combobox', { name: 'Undercover', exact: true }).selectOption('2')
  await page.getByRole('checkbox', { name: /^Fool Dapat/ }).check()
  await page.getByRole('checkbox', { name: /^Fool mendapat kata/ }).uncheck()
  await button(page, 'Lanjut').click()
  await expect(step(page, 'Kata')).toHaveAttribute('aria-current', 'step')
  await expect(page.getByRole('checkbox')).toHaveCount(0)
  await page.getByRole('combobox', { name: 'Kategori' }).selectOption('school')
  await page.getByRole('combobox', { name: 'Kesulitan' }).selectOption('easy')
  await button(page, 'Lanjut').click()
  await expect(step(page, 'Waktu')).toHaveAttribute('aria-current', 'step')
  await page.getByRole('combobox', { name: 'Petunjuk', exact: true }).selectOption('30')
  await page.getByRole('combobox', { name: 'Diskusi', exact: true }).selectOption('60')
  await button(page, 'Pengaturan').click()
  await button(page, 'Cara bermain').click()
  await page.keyboard.press('Escape')
  await button(page, 'Selesai').click()
  await expect(step(page, 'Waktu')).toHaveAttribute('aria-current', 'step')
  await expect(page.getByRole('combobox', { name: 'Petunjuk', exact: true })).toHaveValue('30')
  await button(page, 'Kembali').click()
  await expect(page.getByRole('combobox', { name: 'Kategori' })).toHaveValue('school')
  await step(page, 'Peran').click()
  await expect(page.getByRole('combobox', { name: 'Undercover', exact: true })).toHaveValue('2')
  await expect(page.getByRole('checkbox', { name: /^Fool mendapat kata/ })).not.toBeChecked()
  await step(page, 'Pemain').click()
  await button(page, 'Adit').click()
  await page.getByRole('textbox').fill('Nama baru')
  await step(page, 'Kata').click()
  await step(page, 'Pemain').click()
  await expect(page.getByRole('textbox')).toHaveValue('Nama baru')
  await button(page, 'Simpan').click()
  await step(page, 'Waktu').focus()
  await page.keyboard.press('Enter')
  await button(page, 'Bagikan peran').click()
  const match = await page.evaluate(() => JSON.parse(sessionStorage.getItem('undercover.match.v1')!))
  expect(match.settings).toMatchObject({ undercover: 2, fool: true, foolHasWord: false, category: 'school', difficulty: 'easy', clueSeconds: 30, discussionSeconds: 60 })
  expect(match.players[0].name).toBe('Nama baru')
  expect(match.phase).toBe('word')
  await expect(nav(page)).toHaveCount(0)
})

test('jumping to the last step cannot bypass invalid roles or an empty word pool', async ({ page }) => {
  await page.goto('./')
  await button(page, 'Mulai bermain').click()
  await step(page, 'Peran').click()
  await page.getByRole('combobox', { name: 'Undercover', exact: true }).selectOption('4')
  await expect(button(page, 'Lanjut')).toBeDisabled()
  await step(page, 'Waktu').click()
  await expect(button(page, 'Bagikan peran')).toBeDisabled()
  await expect(page.getByRole('alert')).toContainText('Warga harus lebih banyak')
  await button(page, 'Ubah peran').click()
  await expect(step(page, 'Peran')).toHaveAttribute('aria-current', 'step')
  await page.getByRole('combobox', { name: 'Undercover', exact: true }).selectOption('1')
  await button(page, 'Lanjut').click()
  await page.getByRole('combobox', { name: 'Sumber kata' }).selectOption('custom')
  await expect(button(page, 'Lanjut')).toBeDisabled()
  await step(page, 'Waktu').click()
  await expect(button(page, 'Bagikan peran')).toBeDisabled()
  await button(page, 'Ubah pilihan kata').click()
  await expect(step(page, 'Kata')).toHaveAttribute('aria-current', 'step')
  expect(await page.evaluate(() => sessionStorage.getItem('undercover.match.v1'))).toBeNull()
  await page.getByRole('combobox', { name: 'Sumber kata' }).selectOption('all')
  await button(page, 'Lanjut').click()
  await expect(button(page, 'Bagikan peran')).toBeEnabled()
})

test('setup navigation and actions fit small phones', async ({ page }) => {
  await page.goto('./')
  await button(page, 'Mulai bermain').click()
  for (const [width, height] of [[320, 568], [390, 844], [430, 932]]) {
    await page.setViewportSize({ width, height })
    for (const name of ['Pemain', 'Peran', 'Kata', 'Waktu']) {
      await step(page, name).click()
      await expect(nav(page)).toBeInViewport()
      await expect(nav(page).locator('[aria-current="step"]')).toHaveCount(1)
      expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
      for (const item of await nav(page).getByRole('button').all()) {
        const box = (await item.boundingBox())!
        expect(box.width).toBeGreaterThanOrEqual(44)
        expect(box.height).toBeGreaterThanOrEqual(44)
      }
      const action = button(page, name === 'Waktu' ? 'Bagikan peran' : 'Lanjut')
      if (name === 'Pemain' && height >= 844) {
        await expect(action).toBeInViewport()
        await expect(button(page, 'Beranda')).toBeInViewport()
      }
      await action.scrollIntoViewIfNeeded()
      await expect(action).toBeInViewport()
      await page.screenshot({ path: `test-results/setup-${name}-${width}.png`, fullPage: true })
    }
  }
})
