import { test, expect, type Page } from '@playwright/test'
import type { Match } from '../../src/engine/model'

const key = 'undercover.match.v1'
const button = (p: Page, name: string) => p.getByRole('button', { name, exact: true })
const snapshot = (p: Page): Promise<Match> => p.evaluate((k) => JSON.parse(sessionStorage.getItem(k)!), key)

test('White opener option persists through setup, reload and rematch independently of Fool', async ({ page }) => {
  await page.goto('./')
  await button(page, 'Mulai bermain').click()
  await button(page, 'Lanjut').click()
  const option = page.getByRole('checkbox', { name: /^Mr\. White boleh mulai dulu/ })
  const role = page.getByRole('checkbox', { name: /^Mr\. White Tanpa kata/ })
  await expect(option).toHaveCount(0)
  await role.check()
  await expect(option).toBeChecked()
  await page.getByRole('checkbox', { name: /^Fool Dapat/ }).check()
  const fool = page.getByRole('checkbox', { name: /^Fool boleh mulai dulu/ })
  await expect(fool).toBeChecked()
  await option.uncheck()
  await expect(fool).toBeChecked()
  await fool.uncheck()
  await role.uncheck()
  await expect(option).toHaveCount(0)
  await role.check()
  await expect(option).not.toBeChecked()
  await button(page, 'Kata').click()
  await button(page, 'Peran').click()
  await expect(option).not.toBeChecked()
  await expect(fool).not.toBeChecked()
  await page.setViewportSize({ width: 320, height: 568 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: 'test-results/white-options-320.png', fullPage: true })
  await page.reload()
  await button(page, 'Mulai bermain').click()
  await button(page, 'Lanjut').click()
  await expect(option).not.toBeChecked()
  await expect(fool).not.toBeChecked()
  await button(page, 'Waktu').click()
  await button(page, 'Bagikan peran').click()
  let m = await snapshot(page)
  expect(m.settings).toMatchObject({ white: true, whiteCanStart: false, fool: true, foolCanStart: false })
  expect(['civilian', 'undercover']).toContain(m.players.find((p) => p.id === m.order[0])!.role)
  expect(m.order).toHaveLength(6)
  m.phase = 'result'
  m.winner = 'civilian'
  await page.evaluate(([k, data]) => sessionStorage.setItem(k, data), [key, JSON.stringify(m)])
  await page.reload()
  await button(page, 'Lanjutkan permainan').click()
  await button(page, 'Main lagi').click()
  m = await snapshot(page)
  expect(m.settings).toMatchObject({ whiteCanStart: false, foolCanStart: false })
  expect(['civilian', 'undercover']).toContain(m.players.find((p) => p.id === m.order[0])!.role)
})
